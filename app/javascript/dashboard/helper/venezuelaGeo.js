const ringToPath = ring =>
  ring
    .map(([lat, lng], index) => {
      const { x, y } = toSvg(lat, lng);
      return (index === 0 ? 'M ' : 'L ') + x.toFixed(1) + ',' + y.toFixed(1);
    })
    .join(' ') + ' Z';

export const VENEZUELA_PATH = [VENEZUELA_OUTLINE, ...VENEZUELA_ISLANDS]
  .map(ringToPath)
  .join(' ');
